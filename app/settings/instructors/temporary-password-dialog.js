"use client";

import { useState } from "react";
import { Check, Copy } from "lucide-react";
import { Button } from "@/components/ui/button";
import ConfirmDialog from "@/components/ui/confirm-dialog";
import Alert from "@/components/ui/alert";
import InstructorContext from "@/components/ui/instructor-context";

/**
 * Shows a generated TEMPORARY PASSWORD to the Admin, once, so it can be handed to the instructor (01-product.md §11 "Instructor Login Access").
 *
 * The password lives only in the parent's React state while this dialog is open: it is not put in a URL, storage, a log or a toast, and closing the
 * dialog drops it - it cannot be shown again (a new one is generated by Reset Password). The Copy button uses the clipboard and says whether it
 * worked; the password itself is never announced to assistive technology beyond being in a read-only field the Admin chooses to read.
 *
 * @param {object} props
 * @param {{ full_name: string, email?: string|null, photo_url?: string|null }} props.instructor - whose password this is (the popup's context card).
 * @param {boolean} props.open
 * @param {string|null} props.password
 * @param {string|null} [props.email] - the instructor's sign-in email, shown so both halves of the credentials can be shared.
 * @param {"created"|"reset"} props.kind
 * @param {() => void} props.onClose - the parent must clear the password here.
 */
export default function TemporaryPasswordDialog({ instructor, open, password, email, kind, onClose }) {
  const [copied, setCopied] = useState("idle");

  async function copy() {
    try {
      await navigator.clipboard.writeText(password);
      setCopied("copied");
    } catch {
      setCopied("failed");
    }
  }

  function close() {
    setCopied("idle");
    onClose();
  }

  return (
    <ConfirmDialog
      open={open}
      onOpenChange={(next) => {
        if (!next) close();
      }}
      tone="warning"
      context={<InstructorContext instructor={instructor} />}
      title={kind === "reset" ? "Temporary password generated" : "Temporary password created"}
      description="Share this password with the instructor securely. It is shown only now and cannot be retrieved again."
      note="The instructor must change it the first time they sign in. Until then they cannot use anything else in the app."
      confirmLabel="Done"
      hideCancel
      onConfirm={close}
    >
      <div className="flex flex-col gap-3">
        {email ? (
          <p className="text-body text-text-secondary">
            Sign-in email: <span className="font-medium text-text-primary">{email}</span>
          </p>
        ) : null}
        <div className="flex items-center gap-2">
          <input
            readOnly
            aria-label="Temporary password"
            value={password ?? ""}
            onFocus={(event) => event.target.select()}
            spellCheck={false}
            autoComplete="off"
            className="text-body h-10 min-w-0 flex-1 rounded-input border border-border bg-background px-3 font-mono tracking-wide text-text-primary"
          />
          <Button type="button" variant="outline" onClick={copy}>
            {copied === "copied" ? <Check className="size-4" aria-hidden="true" /> : <Copy className="size-4" aria-hidden="true" />}
            {copied === "copied" ? "Copied" : "Copy"}
          </Button>
        </div>
        <p role="status" className="text-small min-h-5 text-text-secondary">
          {copied === "copied" ? "Copied to the clipboard." : copied === "failed" ? "Could not copy automatically. Select the password and copy it." : ""}
        </p>
        {kind === "reset" ? <Alert variant="info">The previous password no longer works.</Alert> : null}
      </div>
    </ConfirmDialog>
  );
}
